def parse_regional_calques(md_path: Path) -> list:
    """Extracts documented Section 4 regional calque examples from tarraconian_descriptive_title_calques.md."""
    entries = []
    if not md_path.exists():
        return entries
    cur_section = ""
    with open(md_path, "r", encoding="utf-8") as f:
        for line in f:
            s = line.strip()
            if s.startswith("### 4."):
                cur_section = s.lstrip("# ").strip()
            elif s.startswith("| `"):
                parts = [p.strip() for p in s.strip("|").split("|")]
                if len(parts) >= 4:
                    key = parts[0].strip("`")
                    orig = parts[1]
                    calq = re.sub(r"\*\((?:or|Calque|calque)[^)]*\)\*", "", parts[2]).replace("**", "").strip()
                    notes = parts[3]
                    entries.append({
                        "key": key,
                        "region": cur_section,
                        "vanilla_title": orig,
                        "tarraconian_calque": calq,
                        "etymology": notes,
                    })
    return entries


def evaluate_corpus_coverage(gloss_index: dict) -> dict:
    """Measures lexical gloss hits against anachronicity_audit morphemes and NTR etymology_notes."""
    audit_matched = 0
    audit_total_lexical = 0
    audit_unmatched = Counter()

    for p in sorted(glob.glob(str(DATA_DIR / "anachronicity_audit" / "*.json"))):
        with open(p, "r", encoding="utf-8") as f:
            d = json.load(f)
        recs = d.get("baronies", d) if isinstance(d, dict) else d
        if isinstance(recs, dict):
            recs = list(recs.values())
        for b in recs:
            for m in b.get("morphemes", []) or []:
                if not isinstance(m, dict):
                    continue
                g_raw = (m.get("translation") or m.get("gloss") or m.get("meaning") or "").lower().strip()
                if not g_raw or g_raw in GRAMMATICAL_STOPWORDS or any(op in g_raw for op in RULE3_OPAQUE_MARKERS):
                    continue
                audit_total_lexical += 1
                words = re.findall(r"[a-z]+", g_raw)
                # Match multi-word gloss or any lexical headword in gloss_index
                hit = g_raw in gloss_index or any(w in gloss_index for w in words if len(w) >= 3)
                if hit:
                    audit_matched += 1
                else:
                    for w in words:
                        if len(w) >= 4:
                            audit_unmatched[w] += 1

    ntr_quoted_matched = 0
    ntr_quoted_total = 0
    for p in sorted(glob.glob(str(DATA_DIR / "natural_tribal_replacements" / "*.json"))):
        with open(p, "r", encoding="utf-8") as f:
            d = json.load(f)
        recs = d.get("baronies", d) if isinstance(d, dict) else d
        if isinstance(recs, dict):
            recs = list(recs.values())
        for b in recs:
            for cand in b.get("replacement_candidates", []):
                note = cand.get("etymology_notes") or ""
                for m in re.finditer(r"['\"]([a-zA-Z /-]{3,30})['\"]", note):
                    gl = m.group(1).lower().strip()
                    ntr_quoted_total += 1
                    words = re.findall(r"[a-z]+", gl)
                    if gl in gloss_index or any(w in gloss_index for w in words):
                        ntr_quoted_matched += 1

    return {
        "audit_lexical_morphemes_evaluated": audit_total_lexical,
        "audit_lexical_morphemes_matched": audit_matched,
        "audit_lexical_hit_rate_pct": round(100.0 * audit_matched / max(1, audit_total_lexical), 2),
        "ntr_quoted_glosses_evaluated": ntr_quoted_total,
        "ntr_quoted_glosses_matched": ntr_quoted_matched,
        "top_remaining_unmatched_words": audit_unmatched.most_common(25),
    }


def validate_tarraconian_forms(concepts: list):
    """Sanity-checks generated Tarraconian target morphemes against core Chancellery rules."""
    for c in concepts:
        for fld in ("tarr_prefix", "tarr_suffix", "tarr_standalone"):
            val = c[fld]
            if not val:
                continue
            low = val.lower().strip("-")
            if low.endswith(("burg", "berg", "dsch")) or low.startswith(("pf", "schw", "schl", "schm")):
                raise ValueError(f"Phonotactic violation in {c['concept_id']}.{fld}: {val}")


def main():
    parser = argparse.ArgumentParser(description="Generate data/multilingual_morpheme_calque_lexicon.json")
    parser.add_argument("--output", default=str(DATA_DIR / "multilingual_morpheme_calque_lexicon.json"))
    args = parser.parse_args()

    t0 = time.time()
    print("==========================================================")
    print("Generating data/multilingual_morpheme_calque_lexicon.json")
    print("==========================================================")

    concepts_list = build_concepts()
    validate_tarraconian_forms(concepts_list)

    concepts_dict = {}
    gloss_index = {}
    cognate_count = 0

    for c in concepts_list:
        cid = c["concept_id"]
        if cid in concepts_dict:
            raise ValueError(f"Duplicate concept_id: {cid}")
        concepts_dict[cid] = c
        for g in c["english_glosses"]:
            k = g.lower().strip()
            if k not in gloss_index:
                gloss_index[k] = cid
        for forms in c["multilingual_cognates"].values():
            cognate_count += len(forms)

    regional_anchors = parse_regional_calques(CALQUES_MD)
    coverage = evaluate_corpus_coverage(gloss_index)

    payload = {
        "metadata": {
            "sources": [
                "tarraconian_descriptive_title_calques.md",
                "tarraconian_linguistics_guide.md",
                "data/anachronicity_audit/*.json",
                "data/natural_tribal_replacements/*.json",
                "data/sinosphere_kanji_tarraconian.json",
            ],
            "total_concepts": len(concepts_dict),
            "total_english_gloss_aliases": len(gloss_index),
            "total_multilingual_cognates": cognate_count,
            "regional_calque_anchors": len(regional_anchors),
            "corpus_coverage": coverage,
        },
        "concepts": concepts_dict,
        "gloss_index": dict(sorted(gloss_index.items())),
        "grammatical_stopwords": sorted(GRAMMATICAL_STOPWORDS),
        "rule3_opaque_markers": sorted(RULE3_OPAQUE_MARKERS),
        "regional_calque_anchors": regional_anchors,
    }

    out_path = Path(args.output)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2, ensure_ascii=False)

    print(f"-> Wrote {out_path} ({out_path.stat().st_size / 1024:.1f} KB) in {time.time() - t0:.2f}s")
    print(f"   Concepts: {len(concepts_dict)} | Gloss aliases: {len(gloss_index)} | Cognates: {cognate_count} | Anchors: {len(regional_anchors)}")
    print(f"   Audit coverage: {coverage['audit_lexical_morphemes_matched']}/{coverage['audit_lexical_morphemes_evaluated']} ({coverage['audit_lexical_hit_rate_pct']}%)")
    print(f"   Remaining top unmatched: {coverage['top_remaining_unmatched_words'][:10]}")


if __name__ == "__main__":
    main()

def concept(
    cid: str,
    cat: str,
    glosses: list,
    prefix: str,
    suffix: str,
    standalone: str,
    ipa: str,
    gender: str,
    weak_prefix: str = None,
    calquability: str = "always",
    gate: str = None,
    cognates: dict = None,
    example: str = "",
) -> dict:
    """Constructs a normalized Procedure 2 concept record."""
    art_map = {"m": ("de", "dem"), "f": ("de", "der"), "n": ("dat", "dem"), "pl": ("de", "den")}
    art, dat = art_map.get(gender, ("de", "dem"))
    return {
        "concept_id": cid,
        "category": cat,
        "english_glosses": glosses,
        "tarr_prefix": prefix,
        "tarr_suffix": suffix,
        "tarr_standalone": standalone,
        "tarr_ipa": ipa,
        "gender_case": {
            "gender": gender,
            "article": art,
            "dative_article": dat,
            "weak_inflection_prefix": weak_prefix or prefix,
        },
        "calquability": calquability,
        "requires_gate": gate,
        "multilingual_cognates": cognates or {},
        "example": example,
    }


